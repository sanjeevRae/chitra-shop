export function getProduct(id: ProductId): Product | undefined {
  const key = String(id);
  return products.find((p) => String(p.id) === key);
}

/** Product 1 layout doubles as the dynamic template for unknown/Supabase-only IDs. */
export function getProductWithPlaceholder(id: ProductId): Product {
  return getProduct(id) ?? { ...products[0], id: String(id) };
}
